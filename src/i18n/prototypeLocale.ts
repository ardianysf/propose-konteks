export type PrototypeCopyKey = keyof typeof copy

let preference: LocalePreference = readPreference()
const listeners = new Set<() => void>()

export function readPreference(): LocalePreference {
  if (typeof window === 'undefined') return 'auto'
  try {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY)
    return stored === 'auto' || stored === 'en' || stored === 'id' ? stored : 'auto'
  } catch {
    return 'auto'
  }
}

export function resolveLocale(pref: LocalePreference, language?: string): PrototypeLocale {
  if (pref !== 'auto') return pref
  const browserLanguage = language ?? (typeof navigator === 'undefined' ? 'en' : navigator.language)
  return browserLanguage.toLowerCase().startsWith('id') ? 'id' : 'en'
}

export function setLocalePreference(next: LocalePreference): void {
  preference = next
  if (typeof document !== 'undefined') document.documentElement.lang = resolveLocale(next)
  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, next)
  } catch {
    // Storage may be unavailable; keep the in-memory preference.
  }
  listeners.forEach((listener) => listener())
}

export function getLocalePreference(): LocalePreference {
  return preference
}

export function usePrototypeLocale() {
  const pref = useSyncExternalStore(
    (listener) => {
      listeners.add(listener)
      return () => listeners.delete(listener)
    },
    getLocalePreference,
    (): LocalePreference => 'auto',
  )
  const locale = resolveLocale(pref)
  return {
    locale,
    preference: pref,
    setPreference: setLocalePreference,
    t: (key: PrototypeCopyKey) => copy[key][locale],
  }
}

export function resetPrototypeLocaleForTests(): void {
  preference = 'auto'
  listeners.forEach((listener) => listener())
}
