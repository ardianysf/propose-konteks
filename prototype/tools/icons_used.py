"""Collects every Lucide icon the prototype uses and writes src/icons-used.js for the Design system page.
Sources: ic(...) calls (every quoted name inside, so ternaries count), `icon: "name"` in menus, data-lucide="name",
plus icons reached through lookup tables (listed in TABLES). Names are checked against the Lucide build in use."""
import os, re, json, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
LUCIDE = "/tmp/kxtest/node_modules/lucide/dist/esm/icons"
AREA = {"pages-work.js": "Work In Progress, initiative", "pages-more.js": "Activities, session, issues, releases, sign-in", "pages-customize.js": "Customize",
        "pages-settings.js": "Settings", "app-shell.js": "Shell & navigation", "composer.js": "Composer", "ui.js": "Overlays & toasts",
        "pages-catalog.js": "Component catalog", "pages-docs.js": "Pitch & design system", "pages-code.js": "Kode", "data.js": "Data", "app.js": "Pitch bar"}
SKIP = {"code-files.js", "icons-used.js", "inventory.js"}
# Lookup tables whose values are icon names (name of the const -> regex that captures the names).
TABLES = [r"const toneIc = \{([^}]*)\}", r"const SPLIT_PROS = \[(.*?)\];", r"const ACT_ICON = \{([^}]*)\}"]
known, ALIAS = None, {}
if os.path.isdir(LUCIDE):
    known = {f[:-3] for f in os.listdir(LUCIDE) if f.endswith(".js")}
    # Older names (help-circle, more-horizontal) draw the same file; list them under the current name.
    kebab = lambda s: re.sub(r"(?<=[a-z])(?=[A-Z0-9])|(?<=[0-9])(?=[A-Z])", "-", s).lower()
    for m in re.finditer(r"export \{([^}]*)\} from '\./icons/([a-z0-9-]+)\.js'", open(os.path.join(os.path.dirname(LUCIDE), "iconsAndAliases.js")).read()):
        for a in re.findall(r"default as (\w+)", m.group(1)):
            if kebab(a) != m.group(2): ALIAS[kebab(a)] = m.group(2)
def ic_calls(txt):
    out = []
    for m in re.finditer(r"\bic\(", txt):
        i, depth = m.end(), 1
        while i < len(txt) and depth:
            depth += {"(": 1, ")": -1}.get(txt[i], 0); i += 1
        out.append(txt[m.end():i - 1])
    return out
use = {}
for f in sorted(os.listdir(SRC)):
    if not f.endswith(".js") or f in SKIP: continue
    txt = open(os.path.join(SRC, f), encoding="utf-8").read()
    names = []
    for body in ic_calls(txt):
        names += re.findall(r"[\"']([a-z][a-z0-9-]*)[\"']", body)
    names += re.findall(r"\bicon:\s*[\"']([a-z][a-z0-9-]*)[\"']", txt)
    names += re.findall(r"data-lucide=\"([a-z][a-z0-9-]*)\"", txt)
    for t in TABLES:
        for m in re.finditer(t, txt, re.S):
            names += re.findall(r"[\"']([a-z][a-z0-9-]*)[\"']", m.group(1))
    for n in names:
        n = ALIAS.get(n, n)
        if known is not None and n not in known: continue
        use.setdefault(n, set()).add(AREA.get(f, f))
# Icons seen in the rendered demo (tools/icons_crawl.py): catches table-driven icons and Lucide aliases.
RT = os.path.join(ROOT, "tools", "icons_runtime.json")
ROUTE_AREA = {"work": "Work In Progress, initiative", "initiative": "Work In Progress, initiative", "session": "Activities, session, issues, releases, sign-in",
  "activities": "Activities, session, issues, releases, sign-in", "issues": "Activities, session, issues, releases, sign-in", "releases": "Activities, session, issues, releases, sign-in",
  "leaders": "Activities, session, issues, releases, sign-in", "login": "Activities, session, issues, releases, sign-in", "general": "Settings", "plan": "Settings", "usage": "Settings", "budgets": "Settings", "payments": "Settings"}
if os.path.exists(RT):
    for n, routes in json.load(open(RT)).items():
        for r in routes: use.setdefault(ALIAS.get(n, n), set()).add(ROUTE_AREA.get(r, "Customize"))
rows = [[n, sorted(a)] for n, a in sorted(use.items())]
open(os.path.join(SRC, "icons-used.js"), "w").write("/* Generated by tools/icons_used.py: every Lucide icon the demo uses, with where. */\nconst ICONS_USED = " + json.dumps(rows) + ";\n")
print(len(rows), "icons")
